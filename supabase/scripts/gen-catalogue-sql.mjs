/**
 * Turns the mock catalogue into the SQL that seeds the real one.
 *
 * The 28 dishes and 9 badges were written by hand in
 * `apps/mobile/src/mock/`, and retyping them into SQL is exactly the sort of
 * transcription that introduces a dish at 64 kcal instead of 640. This reads
 * the TypeScript directly — the files import types only, so Node's
 * `--experimental-strip-types` can load them with nothing else in the way.
 *
 *   node --experimental-strip-types supabase/scripts/gen-catalogue-sql.mjs \
 *     > supabase/migrations/<timestamp>_seed_catalogue.sql
 *
 * The output is idempotent: every statement is an upsert keyed on the slug, so
 * re-running the migration against a database that already has the catalogue
 * corrects it rather than duplicating it. That is what makes this the right
 * place for the data — a `seed.sql` only runs on `db reset`, and production
 * never resets.
 *
 * KEEPING IT IN STEP
 *
 * Once this has run, the DATABASE is the catalogue. Editing `foods.ts` and
 * regenerating is the way to correct a dish before launch; after launch a
 * correction is its own small migration, because regenerating would also
 * revert anything edited server-side.
 */

import { SEED_ACHIEVEMENTS } from '../../apps/mobile/src/mock/fixtures.ts'
import { FOODS } from '../../apps/mobile/src/mock/foods.ts'

/** Single-quote escaping. Everything here is our own data, but not escaping is how that stops being true. */
const q = (value) => (value == null ? 'null' : `'${String(value).replace(/'/g, "''")}'`)

const lines = []
const w = (line = '') => lines.push(line)

w('-- ---------------------------------------------------------------------------')
w('-- The shared food catalogue and the badge definitions.')
w('--')
w('-- GENERATED by supabase/scripts/gen-catalogue-sql.mjs from')
w('-- apps/mobile/src/mock/{foods,fixtures}.ts. Do not edit by hand: regenerate,')
w('-- or write a follow-up migration for a single correction.')
w('--')
w('-- Idempotent throughout. `on conflict do update` keyed on the slug means a')
w('-- re-run repairs the catalogue instead of duplicating it, which matters')
w('-- because this runs against production exactly like any other migration.')
w('-- ---------------------------------------------------------------------------')
w()
w()
w('-- 1. DISHES ------------------------------------------------------------------')
w('--')
w('-- `owner_id` stays null: these are catalogue rows, visible to every signed-in')
w('-- user. `verified` stays false — the numbers are researched estimates for')
w('-- Malaysian portions, not laboratory values, and the flag should say so.')
w()
w(
  'insert into public.foods (slug, name, icon_set, icon_name, place, kcal, carbs_g, protein_g, fat_g)',
)
w('values')

const foodRows = FOODS.map((food) => {
  const m = food.macros
  return (
    `  (${q(food.id)}, ${q(food.name)}, ${q(food.icon.set)}, ${q(food.icon.name)}, ` +
    `${q(food.place)}, ${m.kcal}, ${m.carbs}, ${m.protein}, ${m.fat})`
  )
})
w(`${foodRows.join(',\n')}`)
w('on conflict (slug) where owner_id is null do update')
w('  set name      = excluded.name,')
w('      icon_set  = excluded.icon_set,')
w('      icon_name = excluded.icon_name,')
w('      place     = excluded.place,')
w('      kcal      = excluded.kcal,')
w('      carbs_g   = excluded.carbs_g,')
w('      protein_g = excluded.protein_g,')
w('      fat_g     = excluded.fat_g;')
w()
w()
w('-- 2. PORTIONS ----------------------------------------------------------------')
w('--')
w('-- Joined back to the dish by slug rather than by a uuid literal: the ids are')
w('-- generated at insert time, and hardcoding them would make this migration')
w('-- reproduce a specific run of itself rather than a state.')
w()
w('insert into public.food_servings (food_id, slug, label, factor, is_default, position)')
w('select f.id, v.slug, v.label, v.factor, v.is_default, v.position')
w('from (values')

const servingRows = []
for (const food of FOODS) {
  food.servings.forEach((serving, index) => {
    // The default is the portion the macros describe, so it is the one whose
    // factor is 1 — asserted here rather than assumed, because a catalogue
    // where the default is not the base rescales the entire dish.
    const isDefault = serving.factor === 1
    servingRows.push(
      `  (${q(food.id)}, ${q(serving.id)}, ${q(serving.label)}, ${serving.factor}, ` +
        `${isDefault}, ${index})`,
    )
  })
}
w(`${servingRows.join(',\n')}`)
w(') as v (food_slug, slug, label, factor, is_default, position)')
w('join public.foods f on f.slug = v.food_slug and f.owner_id is null')
w('on conflict (food_id, slug) do update')
w('  set label      = excluded.label,')
w('      factor     = excluded.factor,')
w('      is_default = excluded.is_default,')
w('      position   = excluded.position;')
w()
w()
w('-- 3. BADGES ------------------------------------------------------------------')
w('--')
w('-- `key` is the i18n key the client already renders, so a badge and its label')
w('-- are named the same thing in both places.')
w()
w('insert into public.achievements (key, icon_set, icon_name, tone, position)')
w('values')

const badgeRows = SEED_ACHIEVEMENTS.map(
  (badge, index) =>
    `  (${q(badge.labelKey)}, ${q(badge.icon.set)}, ${q(badge.icon.name)}, ${q(badge.tone)}, ${index})`,
)
w(`${badgeRows.join(',\n')}`)
w('on conflict (key) do update')
w('  set icon_set  = excluded.icon_set,')
w('      icon_name = excluded.icon_name,')
w('      tone      = excluded.tone,')
w('      position  = excluded.position;')
w()

process.stdout.write(`${lines.join('\n')}\n`)
