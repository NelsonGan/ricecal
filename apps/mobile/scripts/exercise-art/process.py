"""Shrink the raw exercise drawings into what the app ships, and register them.

    uv run scripts/exercise-art/process.py [--raw DIR] [--only id,id]

Reads the 1254px PNGs `generate.mjs` wrote and writes 320px WebPs into
`assets/exercises/`, then rewrites `src/features/workouts/exerciseArt.generated.ts`
from whatever is in that folder.

WHY 320 AND WEBP. The largest the app draws one is the 140pt hero on an
exercise's page, and 320px covers that at @2x and a 106pt tile at @3x. WebP
keeps the alpha and lands around 20 KB a drawing against roughly 90 KB for a
quantised PNG, which over two hundred of them is the difference between a few
megabytes and twenty.

Every drawing is trimmed to its own outline and re-centred with the same
margin, because the model frames each one slightly differently and a list of
them drifting around their tiles looks careless.
"""

import argparse
import os
import re
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
APP = HERE.parent.parent
OUT = APP / "assets" / "exercises"
REGISTRY = APP / "src" / "features" / "workouts" / "exerciseArt.generated.ts"
SIZE = 320
IDENTIFIER = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")
MARGIN = 0.06


def process(source: Path, target: Path) -> None:
    image = Image.open(source).convert("RGBA")
    alpha = image.getchannel("A").point(lambda a: 255 if a > 12 else 0)
    box = alpha.getbbox()
    if box:
        image = image.crop(box)
    width, height = image.size
    side = int(max(width, height) * (1 + 2 * MARGIN))
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(image, ((side - width) // 2, (side - height) // 2), image)
    canvas = canvas.resize((SIZE, SIZE), Image.LANCZOS)
    canvas.save(target, "WEBP", quality=84, method=6)


def write_registry() -> int:
    ids = sorted(path.stem for path in OUT.glob("*.webp"))
    lines = [
        "// Generated by scripts/exercise-art/process.py. Do not edit.",
        "//",
        "// One drawing per built-in exercise, as a static require map so Metro",
        "// bundles exactly these files. An id with no entry draws the category's",
        "// fallback icon instead.",
        "",
        "export const EXERCISE_ART: Readonly<Record<string, number>> = {",
    ]
    for exercise_id in ids:
        # Quoted only where it has to be, which is how Biome formats a key, so
        # regenerating the file does not produce a diff for the formatter to undo.
        key = exercise_id if IDENTIFIER.fullmatch(exercise_id) else f"'{exercise_id}'"
        lines.append(f"  {key}: require('../../../assets/exercises/{exercise_id}.webp'),")
    lines.append("}")
    REGISTRY.write_text("\n".join(lines) + "\n")
    return len(ids)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--raw", default=os.environ.get("EXERCISE_ART_RAW", str(Path.home() / ".cache" / "ricecal" / "exercise-art")))
    parser.add_argument("--only", default="")
    args = parser.parse_args()

    raw = Path(args.raw)
    if not raw.is_dir():
        sys.exit(f"No raw drawings at {raw}. Run generate.mjs first.")
    only = {item for item in args.only.split(",") if item}

    OUT.mkdir(parents=True, exist_ok=True)
    done = 0
    for source in sorted(raw.glob("*.png")):
        if only and source.stem not in only:
            continue
        process(source, OUT / f"{source.stem}.webp")
        done += 1
    count = write_registry()
    print(f"processed {done}, registry lists {count}")


if __name__ == "__main__":
    main()
