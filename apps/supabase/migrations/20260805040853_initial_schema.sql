-- ---------------------------------------------------------------------------
-- The baseline.
--
-- Development ran for a week against a database that was edited directly as
-- often as it was migrated, and the twenty-nine migrations behind this one
-- recorded that history rather than the schema it arrived at: a column added
-- and dropped, a function rewritten four times, one migration that only
-- existed to revoke what an earlier one had granted by accident. None of it
-- has to be replayed, because no environment is behind it — the deployed
-- project is at the end of that chain, and every other database is created
-- from scratch.
--
-- So the chain is gone and this file is what it added up to. It is the
-- concatenation of `schemas/*.sql` in the order `config.toml` declares them,
-- which is the same order `supabase db diff` feeds them to the shadow
-- database, followed by the two things the diff has never been able to see.
-- Applying it to an empty Postgres produces the schema `schemas/` describes,
-- and `db diff` therefore reports nothing.
--
-- It is NOT generated by `db diff`, deliberately. That command drops function
-- ACLs on the floor against a full local stack — five functions once shipped
-- executable by PUBLIC exactly that way — and the `revoke` lines that fix it
-- are already written in the schema files. Copying the files carries them;
-- diffing the files loses them.
--
-- From here the ordinary workflow applies again, and this is the last
-- hand-assembled file: edit `schemas/`, run `pnpm db:diff <name>`, commit what
-- it writes.
--
-- Rebuilt with, if it ever needs to be:
--   cat schemas/*.sql  +  the storage and seed sections at the foot of this file
-- ---------------------------------------------------------------------------


