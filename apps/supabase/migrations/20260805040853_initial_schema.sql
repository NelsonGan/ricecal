-- ---------------------------------------------------------------------------
-- One row per account: who the user is and what their body is doing.
--
-- The split against `user_settings` is not arbitrary. Everything here is an
-- INPUT TO THE CALORIE BUDGET or an identity fact; everything there is a
-- preference that changes only what is displayed. That line is what makes the
-- recompute trigger in 80_targets_sync.sql safe to attach to this table and
-- only this table — a user switching to imperial must not silently rewrite
-- their targets.
--
-- WHAT IS DELIBERATELY NOT HERE
--
-- `weight_kg`. Current weight is the newest row in `weight_logs`, and a copy on
-- this table would be a cache with no invalidation story: the scale syncs a
-- reading, the profile still says what onboarding recorded, and the budget is
-- computed from the stale one. Onboarding writes its weight as the first
-- weigh-in, which also gives the weight chart a starting point for free.
--
-- `age`. Stored as `birth_date`, because an integer age is wrong within a
-- year of being written and nothing would ever correct it. The onboarding
-- stepper still collects a number; the client converts.
-- ---------------------------------------------------------------------------

create table public.profiles (
  id                uuid primary key references auth.users (id) on delete cascade,

  display_name      text not null default '' check (char_length(display_name) <= 60),
  -- An object key in R2, under `avatars/<user>/`, never a URL. Storing the key
  -- is what kept the move off Supabase Storage a change of base URL rather
  -- than a data migration over every row — it has already paid for itself
  -- once. Read and written through the `photos` edge function.
  avatar_path       text,

  sex               public.sex,
  birth_date        date check (birth_date > date '1900-01-01'),
  height_cm         numeric(5, 1) check (height_cm between 80 and 260),
  target_weight_kg  numeric(5, 1) check (target_weight_kg between 20 and 400),
  activity_level    public.activity_level not null default 'light',
  weight_goal       public.weight_goal not null default 'track',

  -- i18n keys into onboarding.foodStyle.tags — the label is translated, the
  -- key is data. An array rather than a join table: it is a short, unordered,
  -- always-read-whole set that nothing else references.
  food_styles       text[] not null default '{}',
  -- Free text from the "how did you hear about us" step. No enum: the answer
  -- list is marketing's to change, and an unknown value must not fail a write.
  referral_source   text,

  -- IANA name. The server needs it to answer "what day is it for this user"
  -- without the client saying so — reminders, the weekly report job, and the
  -- default on `food_logs.log_date` all depend on it. Unconstrained text:
  -- validating against pg_timezone_names needs a non-immutable function, which
  -- a CHECK cannot use.
  timezone          text not null default 'Asia/Kuala_Lumpur',

  -- Null until the last onboarding step commits. The router reads it to decide
  -- between the onboarding stack and the tabs, so it is a timestamp rather
  -- than a boolean: "when" answers questions "whether" cannot.
  onboarded_at      timestamptz,

  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

alter table public.profiles enable row level security;

grant select, insert, update, delete on public.profiles to authenticated;
grant select, insert, update, delete on public.profiles to service_role;

-- No delete policy. An account is deleted through auth, and the cascade takes
-- the profile with it; a client that can delete its own profile row can strand
-- an auth user with no profile and no way to make one.
create policy "profiles: read own"
  on public.profiles for select
  to authenticated
  using ((select auth.uid()) = id);

create policy "profiles: insert own"
  on public.profiles for insert
  to authenticated
  with check ((select auth.uid()) = id);

create policy "profiles: update own"
  on public.profiles for update
  to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);


-- ---------------------------------------------------------------------------
-- schemas/11_user_settings.sql
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- Preferences: everything that changes what the app shows or does, and
-- nothing that changes what the numbers are.
--
-- WHY ONE WIDE TABLE AND NOT SEVERAL
--
-- The Me screens read display, notifications and privacy as separate cards, so
-- the obvious move is a table each. But all of it is strictly 1:1 with the
-- user, always read together on that screen, and always written a field at a
-- time. Separate tables would mean a select, an upsert and a set of policies
-- each, all to be kept identical, in exchange for a normalisation that buys
-- nothing — there is no cardinality to model.
--
-- Adding a preference is a migration either way. Columns are grouped and
-- commented so the file still reads as sections.
--
-- Meal reminder toggles are NOT here. They live on `meal_times` next to the
-- time they fire at, because "remind me about lunch" and "lunch is at 13:00"
-- are one fact, and splitting them means a scheduler joins two tables to
-- answer one question.
-- ---------------------------------------------------------------------------

create table public.user_settings (
  user_id                uuid primary key references auth.users (id) on delete cascade,

  -- Display -----------------------------------------------------------------
  units                  public.unit_system not null default 'metric',
  energy                 public.energy_unit not null default 'kcal',
  -- BCP 47. Matches the i18next resource bundle names; 'en' today.
  language               text not null default 'en',

  -- Notifications -----------------------------------------------------------
  notify_water           boolean not null default true,
  notify_weigh_in        boolean not null default true,
  notify_weekly_report   boolean not null default true,
  -- Local wall-clock times, interpreted in profiles.timezone. `time` and not
  -- `timestamptz`: "no notifications after 22:00" is a rule about the user's
  -- clock, and it stays true when they fly somewhere else.
  quiet_from             time not null default '22:00',
  quiet_to               time not null default '07:00',

  -- Activity ----------------------------------------------------------------
  -- The one movement goal nobody's watch supplies. Apple's Move, Exercise and
  -- Stand goals are set on the watch and arrive per day on `activity_days`; a
  -- step goal is not a HealthKit concept at all and Health Connect has no goals
  -- of any kind, so this is the app's own number and the same one on both
  -- platforms. 8,000 rather than the folk 10,000, which comes from a 1960s
  -- Japanese pedometer's brand name.
  step_goal              integer not null default 8000 check (step_goal between 1000 and 50000),
  -- Whether burned calories extend the day's budget. On by default once a
  -- provider is connected, because a user who linked their watch did it for
  -- this. Off is for somebody who wants the movement charts without the budget
  -- moving under them — the number is still shown, it just stops being spent.
  activity_extends_budget boolean not null default true,

  -- Privacy -----------------------------------------------------------------
  share_with_family      boolean not null default false,
  -- Consent to contribute logged dishes to the catalogue in aggregate. Off by
  -- default, and read server-side before any such job runs — a default of true
  -- would make the consent meaningless.
  anonymous_food_data    boolean not null default false,

  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),

  constraint user_settings_quiet_hours_differ check (quiet_from <> quiet_to)
);

